// Reproduzierbare Sicht- und Interaktionsprüfung des Entwurfs, keine App-Tests.
const { chromium } = require('/Users/landjunge/4AllPass/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const out = __dirname;
(async()=>{
 const browser = await chromium.launch({headless:true});
 const context = await browser.newContext({viewport:{width:1728,height:1240},deviceScaleFactor:1});
 const page = await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(out,'entwurf.html')).href);
 await page.screenshot({path:path.join(out,'hauptansicht-dark.png'),fullPage:true});
 const checks={};
 checks.darkOverflow=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,viewport:innerWidth,scrollHeight:document.documentElement.scrollHeight,height:innerHeight}));
 await page.locator('[data-node="agent-c"]').click();
 checks.partialSelection=(await page.locator('#selection-status').textContent()).includes('lückenhaft');
 await page.screenshot({path:path.join(out,'nachweisluecke-dark.png'),fullPage:true});
 await page.locator('[data-node="process"]').focus();await page.keyboard.press('Enter');
 checks.keyboardSelection=(await page.locator('#selection-title').textContent())==='python3.12';
 await page.locator('#zoom-in').click();checks.zoom=(await page.locator('#zoom-value').textContent())==='115 %';
 await page.locator('#fit').click();checks.fit=(await page.locator('#zoom-value').textContent())==='100 %';
 await page.locator('#search').fill('8421');checks.search=await page.locator('[data-node="agent-a"]').evaluate(n=>n.classList.contains('dimmed'));
 await page.locator('#search').fill('');
 await page.locator('#filter').click();checks.filter=await page.locator('[data-node="action"]').evaluate(n=>n.classList.contains('dimmed'));
 await page.locator('#filter').click();await page.locator('#filter').click();
 await page.locator('[data-node="action"]').click();
 await page.locator('#theme').click();await page.screenshot({path:path.join(out,'hauptansicht-light.png'),fullPage:true});
 checks.light=await page.evaluate(()=>document.documentElement.dataset.theme==='light');
 await page.locator('#host').click();await page.screenshot({path:path.join(out,'testhost-light.png'),fullPage:true});
 checks.permissionsNoAction=(await page.locator('#sheet').textContent()).includes('keine Systemfreigaben');
 await page.keyboard.press('Escape');checks.escape=await page.locator('#sheet').evaluate(n=>!n.open);
 await page.locator('#theme').click();await page.locator('#scenario').selectOption('master');
 checks.masterUnknown=(await page.locator('#selection-status').textContent()).includes('unbekannt');
 checks.masterNoLiveMetric=(await page.locator('#actions-value').textContent())==='—';
 await page.screenshot({path:path.join(out,'aktueller-vertrag-dark.png'),fullPage:true});
 await page.locator('[data-tab="raw"]').click();checks.rawTab=await page.locator('#raw-inspector').isVisible();
 await page.locator('#scenario').selectOption('demo');
 await page.locator('#inspector-toggle').click();checks.inspectorToggle=await page.locator('.inspector').isHidden();
 await page.locator('#inspector-toggle').click();
 await page.locator('#sidebar-toggle').click();checks.sidebarToggle=await page.locator('.sidebar').isHidden();
 await page.locator('#sidebar-toggle').click();
 await page.locator('#stage').click({position:{x:400,y:220},button:'right'}); // Hintergrund bleibt ohne Kontextaktion.
 await page.locator('[data-node="authority"]').click({button:'right'});checks.contextMenu=await page.locator('#sheet').isVisible();await page.keyboard.press('Escape');
 await page.locator('[data-node="action"]').click();
 await page.setViewportSize({width:1280,height:900});
 checks.compact=await page.evaluate(()=>({viewport:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
 await page.screenshot({path:path.join(out,'kompakt-dark.png'),fullPage:true});
 const big=await browser.newContext({viewport:{width:2560,height:1440},deviceScaleFactor:2});const bigPage=await big.newPage();await bigPage.goto(pathToFileURL(path.join(out,'entwurf.html')).href);
 await bigPage.screenshot({path:path.join(out,'hauptansicht-dark-5k.png'),fullPage:true});
 checks.fiveK=await bigPage.evaluate(()=>({viewport:innerWidth,height:innerHeight,devicePixelRatio,scrollWidth:document.documentElement.scrollWidth,scrollHeight:document.documentElement.scrollHeight}));
 checks.pageErrors=errors;
 checks.scope='Browser-Entwurf geprüft; keine native oder R9-M380-Performance-Messung';
 fs.writeFileSync(path.join(out,'pruefung.json'),JSON.stringify(checks,null,2)+'\n','utf8');
 console.log(JSON.stringify(checks,null,2));await browser.close();
 if(errors.length||Object.entries(checks).some(([k,v])=>typeof v==='boolean'&&!v))process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1);});
